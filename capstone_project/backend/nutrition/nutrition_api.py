def generate_final_response(menu_data_structure):
    """
    구조화된 메뉴 데이터(Dict)를 받아서 JSON 응답을 생성합니다.
    """
    final_menu = []

    # 1. 구역(Section) 반복: 휘당, Chef & U ...
    for section, time_data in menu_data_structure.items():
        # 2. 시간(Time) 반복: 아침, 점심 ...
        for time, menu_list in time_data.items():
            # 3. 메뉴 리스트 반복
            for name in menu_list:
                cleaned_name_key = name.replace(" ", "").replace("/", "").replace(",", "").strip()
                
                # 영양 정보 가져오기
                nutrition = NUTRITION_MANUAL_DB.get(cleaned_name_key, {
                    "칼로리": "정보 없음", "단백질": "정보 없음", "알레르기_정보": "정보 없음", "탄수화물": "정보 없음", "지방": "정보 없음", "정보": ""
                })

                final_item = {
                    "메뉴 이름": name,
                    "가격": "5,000", 
                    "식당 구분": section,  # [추가] 휘당, Chef & U 등
                    "식사 시간": time,     # [추가] 아침, 점심 등
                    "영양 정보": {
                        "칼로리": nutrition.get('칼로리', '정보 없음'),
                        "단백질": nutrition.get('단백질', '정보 없음'),
                        "탄수화물": nutrition.get('탄수화물', '정보 없음'),
                        "지방": nutrition.get('지방', '정보 없음'),
                        "알레르기_정보": nutrition.get('알레르기_정보', '정보 없음'),
                        "정보": nutrition.get('정보', '')
                    }
                }
                final_menu.append(final_item)

    final_response = {
        "날짜": datetime.now().strftime("%Y-%m-%d"),
        "식당": "한림대 학생 식당",
        "메뉴 목록": final_menu
    }

    return json.dumps(final_response, indent=4, ensure_ascii=False)

